/** 한 줄을 갈래에 놓는다. 걸리는 낱말이 없으면 'new'. */
export function place(line) {
  const s = String(line || '');
  let best = null;
  for (const lane of lanes) {
    let score = 0;
    const got = [];
    for (const k of lane.kw) if (s.includes(k)) { score += k.length; got.push(k); }
    if (score && (!best || score > best.score)) best = { key: lane.key, score, got };
  }
  return best || { key: 'new', score: 0, got: [] };
}
